const log = createLogger('server');

export const SERVER_NAME = 'sherlock';
export const SERVER_VERSION = '1.0.0';

const INSTRUCTIONS = `S.H.E.R.L.O.C.K. - Sprint Health, Execution, Risk, Logistics, Operations & Coordination Knowledge.

SCOPE
All Azure DevOps tools operate on the configured organization, project and team (ADO_ORGANIZATION / ADO_PROJECT / ADO_TEAM). You never need to pass organization, project or team unless a tool explicitly supports an override.

AZURE DEVOPS WRITES — MANDATORY WORKFLOW
Every Azure DevOps mutation follows: understand -> search existing work -> propose -> validate -> SHOW THE PROPOSAL TO THE USER -> explicit user approval -> confirm -> write -> verify.
The server enforces this in code, not by instruction. A prepared operation sits in AWAITING_CONFIRMATION and the Azure DevOps write client refuses any mutation that is not inside an approved, confirmed operation (WRITE_NOT_AUTHORIZED).
The user's original request is never approval. "Create work items for X", "update this", "go ahead and use Sherlock" all start planning; they do not authorise a write. Present the prepared proposal and wait for the user to approve it before calling any confirm tool. Editing a plan invalidates every confirmation issued for the previous version.

CONTROLLED WRITE TOOLS
- \`sherlock_prepare_create_work_item\` (Epic, Feature, User Story, Task, Bug) — preview only
- \`sherlock_prepare_update_work_item\` — listed fields and tags
- \`sherlock_prepare_relationship_change\` / \`sherlock_prepare_set_parent\` — parent or predecessor only
- \`sherlock_prepare_add_comment\` — discussion comment after confirmation
- \`sherlock_get_write_status\` / \`sherlock_retry_write\`
- \`sherlock_confirm_write\` — the only step that mutates a single prepared work item
- \`sherlock_plan_work\` / \`sherlock_get_work_plan\` / \`sherlock_modify_work_plan\` / \`sherlock_validate_work_item_plan\` — propose and validate a tree; does not deploy
- \`sherlock_prepare_deployment\` then \`sherlock_confirm_deployment\` — deploys a stored valid plan. \`sherlock_retry_deployment\` retries failed items only.
Never invent a JSON Patch, never delete, never update arbitrary fields.

SAVED QUERIES
\`create_ado_query\` creates or reuses a saved query under \`My Queries/{ADO_TEAM}\`. Do not use Shared Queries unless explicitly asked. If the folder cannot be used, report QUERY_FOLDER_NOT_FOUND and do not invent a URL.

REAL DATA VS ANALYSIS
Tools prefixed \`ado_\` return measured Azure DevOps data. Tools prefixed \`analysis_\`, \`tl_analyze_\` and the review generators return an envelope with a \`facts\` block (measured) plus \`observations\`, \`concerns\` and \`recommendations\` (generated by this server's heuristics, with the thresholds stated in \`methodology\`). Keep the two apart when you answer, and never invent a work item, person, date or metric that is not in the tool output. If a value could not be measured, the tool says so - pass that on rather than estimating.

SKILLS COME FIRST FOR RECURRING WORKFLOWS
When asked for a briefing, workload, sprint, backlog, deadline or composed review, call \`skill_execute\` with the skill name (built-in or custom). Do not chain many \`ado_*\` tools for those workflows. Use custom skill tools to show, compose, create and manage reusable analysis skills.

WHERE TO START
- "How is my team doing?" -> \`skill_execute\` \`daily-standup-starter\` or \`team-morning-brief\`
- "How is the project?" -> \`skill_execute\` \`project-health-analysis\`
- "Who is overloaded?" -> \`skill_execute\` \`workload-analysis\`
- "What is at risk?" -> \`skill_execute\` \`deadline-risk-analysis\`
- "Who should take #1234?" -> \`skill_execute\` \`work-assignment-recommendation\`
- Combine skills -> \`sherlock_compose_skill\` (confirm=false, then true)
- One-off lookups -> \`ado_*\` tools
- Prompts (daily_team_review, sprint_review, tl_weekly_review) still orchestrate workflows.`;

export interface BuildServerOptions {
    /** Skip opening the SQLite audit database. Used by tests that stub the repositories. */
    skipDatabaseInit?: boolean;
}

/**
 * Builds the MCP server: registers every tool, resource and prompt, then audits the
 * resulting tool surface against the read-only policy before returning.
 */
export function buildServer(options: BuildServerOptions = {}): McpServer {
    const config = getConfig();

    if (!options.skipDatabaseInit) {
        // Open (and migrate) the audit database eagerly so a misconfigured
        // DATABASE_URL fails at startup rather than mid-conversation.
        getDatabase();
        InternalSkillRegistry.loadFromDatabase();
    }

    const server = new McpServer(
        { name: SERVER_NAME, version: SERVER_VERSION },
        {
            instructions: INSTRUCTIONS,
            capabilities: { tools: {}, resources: {}, prompts: {}, logging: {} }
        }
    );

    clearRegisteredToolMeta();

    registerAdoProjectTools(server);
    registerAdoWorkItemTools(server);
    registerQueryTools(server);
    registerAdoWriteTools(server);
    registerWorkItemWriteTools(server);
    registerPlanningTools(server);
    registerDeploymentTools(server);
    registerAnalysisTools(server);
    registerGovernanceTools(server);
    registerTeamLeadTools(server);
    registerHealthTools(server);
    registerSkillTools(server);
    registerCustomSkillTools(server);
    registerResources(server);
    registerSkillResources(server);
    registerPrompts(server);

    assertReadOnlyToolSurface();
    assertSkillCatalogueIsValid();

    const tools = getRegisteredToolMeta();
    log.info('MCP server ready', {
        name: SERVER_NAME,
        version: SERVER_VERSION,
        tools: tools.length,
        readOnlyTools: tools.filter(tool => tool.readOnly).length,
        skills: getSkills().length,
        organization: config.ado.organization,
        project: config.ado.project,
        team: config.ado.team,
        adoConfigured: config.ado.configured
    });

    return server;
}

/**
 * Startup guarantee: no registered tool may look like an Azure DevOps mutation or
 * accept HTTP-level parameters. A violation aborts startup.
 */
export function assertReadOnlyToolSurface(): void {
    const tools = getRegisteredToolMeta();
    const violations = auditToolSurface(tools);
    if (violations.length > 0) {
        throw new AppError(
            'READ_ONLY_VIOLATION',
            `Read-only tool surface audit failed:\n${violations.map(violation => `  - ${violation.tool}: ${violation.reason}`).join('\n')}`
        );
    }

    // Permitted non-read-only tool: controlled saved query creation.
    const mutating = tools.filter(tool => !tool.readOnly).map(tool => tool.name);
    const allowedMutating = [
        'create_ado_query',
        'sherlock_confirm_write',
        'sherlock_retry_write',
        'sherlock_confirm_deployment',
        'sherlock_retry_deployment'
    ];
    const invalidMutating = mutating.filter(name => !allowedMutating.includes(name));
    
    if (invalidMutating.length > 0) {
        throw new AppError(
            'READ_ONLY_VIOLATION',
            `Only ${allowedMutating.join(' and ')} may be non-read-only, but found: ${invalidMutating.join(', ')}.`
        );
    }
}

/**
 * Startup guarantee for the skill catalogue: every skill is fully specified and
 * references only tools this server actually exposes. A skill that names a
 * missing tool would instruct the model to call something imaginary, so it
 * aborts startup rather than reaching a client.
 */
export function assertSkillCatalogueIsValid(): void {
    const issues = validateSkills(
        getSkills(),
        getRegisteredToolMeta().map(tool => tool.name)
    );
    if (issues.length > 0) {
        throw new AppError(
            'INVALID_INPUT',
            `Skill catalogue validation failed:\n${issues.map(issue => `  - ${issue.skill}: ${issue.reason}`).join('\n')}`
        );
    }
}
